#!/usr/bin/env bash
# quality-battery.sh <tag> [port]
#
# Gross-failure battery for a running llama-server.
# Detects catastrophic failures only: needle-style probes score 100% for
# every quantized KV type, so a pass tie cannot rank the configs — the
# quality ordering is prior-only (see notes/0002).
#
# Tests:
#   N1  needle-in-a-haystack, fact hidden ~25% into a long filler context
#   N2  same, fact hidden ~90% deep (recurrent-state / long-context check)
#   T1  tool-calling round (jinja template + tools array)
#   V1  vision: 4x4 checkerboard PNG, ask for grid size and colors
#
# Filler and needle are deterministic (generated by the embedded python).
# Results append to artifacts/quality-<tag>.txt (package root)
set -uo pipefail
TAG="$1"; PORT="${2:-8080}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SCRATCH="$ROOT/artifacts"
OUT="$SCRATCH/quality-$TAG.txt"
mkdir -p "$SCRATCH"

python3 - "$SCRATCH" <<'PYEOF'
import json, sys, struct, zlib, base64, random
scratch = sys.argv[1]

# ---------- deterministic filler + needles ----------
para = ("The maintenance log for building C lists routine inspections of the "
        "ventilation system, notes about elevator servicing schedules, and "
        "reminders that the parking garage gate code rotates on the first "
        "Monday of every month. Staff are asked to log any anomalies in the "
        "shared ledger and to attach photographs where applicable. The ledger "
        "is reviewed weekly by the facilities coordinator. ")
random.seed(42)
def build(frac):
    n = 1500  # paragraphs; ~ 30k+ tokens per 1000 paragraphs approx
    cut = int(n * frac)
    parts = []
    for i in range(n):
        if i == cut:
            parts.append("SPECIAL NOTICE: the temporary security checkpoint "
                         "code is ZEBRA-7491 and it expires on October 3. ")
        parts.append(para)
    text = " ".join(parts)
    return text
open(f"{scratch}/qb-n1-prompt.txt", "w").write(build(0.25))
open(f"{scratch}/qb-n2-prompt.txt", "w").write(build(0.90))

# ---------- tiny deterministic PNG (4x4 checkerboard, black/white) ----------
def png(path):
    W = H = 4
    rows = []
    for y in range(H):
        row = bytearray([0])  # filter none
        for x in range(W):
            v = 255 if (x + y) % 2 == 0 else 0
            row += bytes([v, v, v])
        rows.append(bytes(row))
    raw = b"".join(rows)
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)
    data = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))
    open(path, "wb").write(data)
    return base64.b64encode(data).decode()
b64 = png(f"{scratch}/qb-checker.png")
open(f"{scratch}/qb-v1-image.txt", "w").write(b64)
PYEOF

ask() { # $1=label $2=payload-json-file
  {
    echo "=== $TAG / $1 ==="
    curl -sS -m 600 "http://127.0.0.1:$PORT/v1/chat/completions" \
      -H 'Content-Type: application/json' \
      -d @"$2" | python3 -c '
import json,sys
try:
    r = json.load(sys.stdin)
    ch = r["choices"][0]
    print("content:", (ch["message"].get("content") or "")[:400])
    tc = ch["message"].get("tool_calls")
    if tc: print("tool_calls:", json.dumps(tc)[:400])
    u = r.get("usage", {})
    print("usage:", json.dumps(u))
except Exception as e:
    print("PARSE_ERROR:", e, "| raw:", sys.stdin.read()[:200])
'
  } >> "$OUT"
}

mkjson() { python3 - "$1" "$2" "$SCRATCH" <<'PYEOF'
import json, sys
out_path, kind = sys.argv[1], sys.argv[2]
scratch = sys.argv[3]
base = {"model": "local", "temperature": 0.0, "max_tokens": 200, "stream": False}
if kind in ("n1", "n2"):
    prompt = open(f"{scratch}/qb-{kind}-prompt.txt").read()
    body = base | {"messages": [
        {"role": "user", "content": prompt + "\n\nQuestion: What is the temporary "
         "security checkpoint code and when does it expire? Answer in one line."}]}
elif kind == "t1":
    body = base | {"messages": [
        {"role": "user", "content": "What is the weather in Paris right now? "
         "Use the provided tool."}],
        "tools": [{"type": "function", "function": {"name": "get_weather",
            "description": "Get current weather for a city",
            "parameters": {"type": "object", "properties": {
                "city": {"type": "string"}}, "required": ["city"]}}}]}
elif kind == "v1":
    b64 = open(f"{scratch}/qb-v1-image.txt").read()
    body = base | {"messages": [
        {"role": "user", "content": [
            {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{b64}"}},
            {"type": "text", "text": "What is the size of the checkered grid in "
             "this image, and which colors alternate? Answer in one line."}]}]}
open(out_path, "w").write(json.dumps(body))
PYEOF
}

echo "=== quality battery $TAG $(date -u +%FT%TZ) ===" > "$OUT"
for k in n1 n2 t1 v1; do
  mkjson "$SCRATCH/qb-req.json" "$k"
  ask "$k" "$SCRATCH/qb-req.json"
done
cat "$OUT"
echo "battery done: $TAG"
